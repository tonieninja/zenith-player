export function streamStuckMessage(
  t: typeof en,
  kind: string | null | undefined,
  signedIn: boolean
): string {
  if (kind === 'network') return t.streamBlockedNetwork;
  if (kind === 'bot') return signedIn ? t.streamBlockedBotSignedIn : t.streamBlockedBot;
  if (kind === 'component') return t.streamBlockedComponent;
  if (kind === 'age') return signedIn ? t.streamAgeRestrictedSignedIn : t.streamAgeRestricted;
  if (kind === 'gone') return t.streamGone;
  if (kind === 'region') return t.streamRegion;
  if (kind === 'ratelimit') return t.streamRateLimited;
  return signedIn ? t.streamUnavailableStuckSignedIn : t.streamUnavailableStuck;
}

// usunięty film, blokada regionu i zła sieć nie znikają po zalogowaniu, więc tam przycisk tylko by mylił
export function streamStuckAsksSignIn(kind: string | null | undefined, signedIn: boolean): boolean {
  return !signedIn && !['network', 'component', 'gone', 'region', 'ratelimit'].includes(kind ?? '');
}

// te powody są pewne już po pierwszej porażce, a ogólne „pomijam” nie mówi, że ponowna próba nic nie da
export function isDefiniteStreamFailure(kind: string | null | undefined): boolean {
  return kind === 'age' || kind === 'gone' || kind === 'region' || kind === 'ratelimit';
}

// komunikaty z Rusta i API są po angielsku; znane przypadki tłumaczymy, resztę pokazujemy bez zmian
export function errorText(t: typeof en, e: unknown): string {
  const raw = String((e as Error)?.message ?? e);
  const http = /\bhttp (\d{3})\b/i.exec(raw);
  if (/already downloading/i.test(raw)) return t.errAlreadyDownloading;
  if (/already offline/i.test(raw)) return t.errAlreadyOffline;
  if (/no stream|empty download/i.test(raw)) return t.errNoStream;
  if (/cancelled/i.test(raw)) return t.errCancelled;
  if (/last\.fm api key/i.test(raw)) return t.errLastfmNoKey;
  if (/last\.fm user name/i.test(raw)) return t.errLastfmNoUser;
  if (/import already running/i.test(raw)) return t.errImportRunning;
  if (/not a zenith backup/i.test(raw)) return t.errNotBackup;
  if (/backup too big/i.test(raw)) return t.errBackupTooBig;
  if (/not connected/i.test(raw)) return t.errNotConnected;
  if (/port \d+.*(10048|in use|busy)/i.test(raw)) return t.errPortBusy;
  if (http) return t.errHttp.replace('{code}', http[1]);
  if (/timed? ?out/i.test(raw)) return t.errTimeout;
  if (/error sending request|dns|connection refused|network|offline/i.test(raw))
    return t.errNetwork;
  return raw;
}

